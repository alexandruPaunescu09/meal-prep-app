-- Shared schema for food diary stories built in parallel:
--   FD-5  label photo -> pending food (photo columns, bucket, parse log)
--   FD-6  recents / favorites / copy (food_favorites)
--   FD-12 admin food moderation (reads the photos, repoints favorites when merging foods)
-- One migration so the three stories agree on names; each story adds only its own logic.

-- ---------------------------------------------------------------------------
-- foods: photos a label-photo food was read from (storage keys in food-label-photos)
-- ---------------------------------------------------------------------------
ALTER TABLE foods
  ADD COLUMN IF NOT EXISTS label_photo_path TEXT,
  ADD COLUMN IF NOT EXISTS front_photo_path TEXT;

-- ---------------------------------------------------------------------------
-- Private bucket for nutrition-label photos.
-- Path convention: {client_id}/{food_id}/label.jpg and {client_id}/{food_id}/front.jpg
-- (food_id may be generated by the client before the foods row exists).
-- Customers read/write only inside their own client_id folder; admin has full access.
-- ---------------------------------------------------------------------------
INSERT INTO storage.buckets (id, name, public)
VALUES ('food-label-photos', 'food-label-photos', FALSE)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "Customer read own label photos"
  ON storage.objects FOR SELECT
  USING (
    bucket_id = 'food-label-photos'
    AND current_client_id()::text = (storage.foldername(name))[1]
  );

CREATE POLICY "Customer upload own label photos"
  ON storage.objects FOR INSERT
  WITH CHECK (
    bucket_id = 'food-label-photos'
    AND current_client_id()::text = (storage.foldername(name))[1]
  );

CREATE POLICY "Customer update own label photos"
  ON storage.objects FOR UPDATE
  USING (
    bucket_id = 'food-label-photos'
    AND current_client_id()::text = (storage.foldername(name))[1]
  );

CREATE POLICY "Customer delete own label photos"
  ON storage.objects FOR DELETE
  USING (
    bucket_id = 'food-label-photos'
    AND current_client_id()::text = (storage.foldername(name))[1]
  );

CREATE POLICY "Admin full access on label photos"
  ON storage.objects FOR ALL
  USING (bucket_id = 'food-label-photos' AND is_admin())
  WITH CHECK (bucket_id = 'food-label-photos' AND is_admin());

-- ---------------------------------------------------------------------------
-- food_label_parses: one row per label-photo parse attempt, for the per-customer daily limit
-- (FD-5: at most 10 per customer per day). Written server-side with the service client only.
-- ---------------------------------------------------------------------------
CREATE TABLE food_label_parses (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  client_id UUID NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  model TEXT,
  outcome TEXT NOT NULL CHECK (outcome IN ('ok', 'unreadable', 'error')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_food_label_parses_client ON food_label_parses (client_id, created_at DESC);

ALTER TABLE food_label_parses ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admin read" ON food_label_parses
  FOR SELECT USING (is_admin());

-- ---------------------------------------------------------------------------
-- food_favorites: a customer's starred catalog items (FD-6). Exactly one target per row.
-- CASCADE on every target: a deleted or merged-away item simply stops being a favorite
-- (FD-12's merge repoints food favorites to the surviving food before deleting the duplicate).
-- ---------------------------------------------------------------------------
CREATE TABLE food_favorites (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  client_id UUID NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  food_id UUID REFERENCES foods(id) ON DELETE CASCADE,
  ingredient_id UUID REFERENCES ingredients(id) ON DELETE CASCADE,
  recipe_id UUID REFERENCES recipes(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT food_favorites_one_target CHECK (num_nonnulls(food_id, ingredient_id, recipe_id) = 1)
);

CREATE UNIQUE INDEX food_favorites_client_food
  ON food_favorites (client_id, food_id) WHERE food_id IS NOT NULL;
CREATE UNIQUE INDEX food_favorites_client_ingredient
  ON food_favorites (client_id, ingredient_id) WHERE ingredient_id IS NOT NULL;
CREATE UNIQUE INDEX food_favorites_client_recipe
  ON food_favorites (client_id, recipe_id) WHERE recipe_id IS NOT NULL;

ALTER TABLE food_favorites ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admin full access" ON food_favorites
  FOR ALL USING (is_admin()) WITH CHECK (is_admin());

CREATE POLICY "Customer manage own" ON food_favorites
  FOR ALL USING (client_id = current_client_id())
  WITH CHECK (client_id = current_client_id());
